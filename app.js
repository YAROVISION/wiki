const modalClose = document.getElementById('modal-close');
const modalColLetter = document.getElementById('modal-col-letter');
const modalColIndex = document.getElementById('modal-col-index');
const modalColMain = document.getElementById('modal-col-main');
const modalColSub = document.getElementById('modal-col-sub');
const modalColInstruction = document.getElementById('modal-col-instruction');
const modalCopyBtn = document.getElementById('modal-copy-btn');
const toastNotification = document.getElementById('toast');

// Initialize App
document.addEventListener('DOMContentLoaded', () => {
  // Load saved theme
  const savedTheme = localStorage.getItem('coffee-theme') || 'dark';
  setTheme(savedTheme);
  
  // Set up event listeners
  searchInput.addEventListener('input', handleSearch);
  
  filterAll.addEventListener('click', () => setFilter('all'));
  filterFirstHalf.addEventListener('click', () => setFilter('1-е півріччя'));
  filterSecondHalf.addEventListener('click', () => setFilter('2-е півріччя'));
  
  btnGridView.addEventListener('click', () => setViewMode('grid'));
  btnTableView.addEventListener('click', () => setViewMode('table'));
  
  themeToggle.addEventListener('click', toggleTheme);
  
  modalClose.addEventListener('click', closeModal);
  modalOverlay.addEventListener('click', (e) => {
    if (e.target === modalOverlay) closeModal();
  });
  
  // Keyboard esc to close modal
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modalOverlay.classList.contains('show')) {
      closeModal();
    }
  });

  // Back to Top button scroll handler
  window.addEventListener('scroll', () => {
    if (window.scrollY > 300) {
      backToTopBtn.classList.add('show');
    } else {
      backToTopBtn.classList.remove('show');
    }
  });

  // Back to Top button click handler
  backToTopBtn.addEventListener('click', () => {
    window.scrollTo({
      top: 0,
      behavior: 'smooth'
    });
  });

  // Initial render
  renderLettersNav();
  render();
});

// Theme Logic
function setTheme(theme) {
  state.theme = theme;
  if (theme === 'light') {
    document.body.classList.add('light-theme');
  } else {
    document.body.classList.remove('light-theme');
  }
  localStorage.setItem('coffee-theme', theme);
}

// Search Logic
function handleSearch(e) {
  state.searchTerm = e.target.value.toLowerCase().trim();
  render();
}

// Filter Logic
function setFilter(filterType) {
  state.activeFilter = filterType;
  
  // Update UI buttons
  filterAll.classList.toggle('active', filterType === 'all');
  filterFirstHalf.classList.toggle('active', filterType === '1-е півріччя');
  filterSecondHalf.classList.toggle('active', filterType === '2-е півріччя');
  
  render();
}

// View Mode Logic
function setViewMode(mode) {
  state.viewMode = mode;
  btnGridView.classList.toggle('active', mode === 'grid');
  btnTableView.classList.toggle('active', mode === 'table');
  render();
}

// Render Quick Letters Navigation List
function renderLettersNav() {
  const container = document.getElementById('letters-nav-container');
  if (!container) return;
  
  container.innerHTML = '';
  
  const uniqueLetters = [];
  const letterMap = new Map();
  
  state.columns.forEach(col => {
    if (!letterMap.has(col.col_letter)) {
      letterMap.set(col.col_letter, col);
      uniqueLetters.push(col.col_letter);
    }
  });
  
  uniqueLetters.forEach(letter => {
    const a = document.createElement('a');
    a.href = `#col-${letter}`;
    a.className = 'letter-nav-link';
    a.textContent = letter;
    
    a.addEventListener('click', (e) => {
      e.preventDefault();
      
      // Reset state filters so target column is visible
      state.activeFilter = 'all';
      state.searchTerm = '';
      
      // Update UI inputs
      searchInput.value = '';
      filterAll.classList.add('active');
      filterFirstHalf.classList.remove('active');
      filterSecondHalf.classList.remove('active');
      
      render();
      
      // Find and scroll to element
      const targetId = `col-${letter}`;
      const element = document.getElementById(targetId);
      if (element) {
        element.scrollIntoView({ behavior: 'smooth', block: 'center' });
        
        // Apply a highlight animation
        element.classList.add('highlight-flash');
        setTimeout(() => {
          element.classList.remove('highlight-flash');
        }, 1500);
      }
    });
    
    container.appendChild(a);
  });
}

// Helper function to highlight matching search term
function highlightText(text, search) {
  if (!search) return text;
  
  // Escape special regex chars
  const escapedSearch = search.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');
  const regex = new RegExp(`(${escapedSearch})`, 'gi');
  return text.replace(regex, '<mark class="search-highlight">$1</mark>');
}

// Render Logic
function render() {
  const filtered = state.columns.filter(col => {
    // Apply type filter
    const matchesFilter = state.activeFilter === 'all' || col.title_sub === state.activeFilter;
    
    // Apply search filter
    const matchesSearch = !state.searchTerm || 
      col.col_letter.toLowerCase().includes(state.searchTerm) || 
      col.title_main.toLowerCase().includes(state.searchTerm) ||
      col.instruction.toLowerCase().includes(state.searchTerm) ||
      (col.title_sub && col.title_sub.toLowerCase().includes(state.searchTerm));
      
    return matchesFilter && matchesSearch;
  });

  // Clear previous output
  resultsContainer.innerHTML = '';

  if (filtered.length === 0) {
    resultsContainer.innerHTML = `
      <div class="empty-state">
        <i class="fas fa-search-minus"></i>
        <h3>Граф не знайдено</h3>
        <p>Спробуйте змінити пошуковий запит або вибрати інший фільтр</p>
      </div>
    `;
    return;
  }

  if (state.viewMode === 'grid') {
    renderGrid(filtered);
  } else {
    renderTable(filtered);
  }
}

// Render Card Grid
function renderGrid(data) {
  const grid = document.createElement('div');
  grid.className = 'columns-grid';
  
  data.forEach((col, index) => {
    const card = document.createElement('div');
    card.className = 'col-card fade-in-item';
    card.style.animationDelay = `${index * 0.012}s`;
    card.id = `col-${col.col_letter}`;
    
    // Determine subtitle styling
    const subClass = col.title_sub === '1-е півріччя' ? 'first-half' : 'second-half';
    const subText = col.title_sub || 'Загальне';
    
    const highlightedMain = highlightText(col.title_main, state.searchTerm);
    const highlightedSub = highlightText(subText, state.searchTerm);
    const highlightedLetter = highlightText(col.col_letter, state.searchTerm);
    const highlightedInstruction = highlightText(col.instruction, state.searchTerm);

    card.innerHTML = `
      <div class="card-header-row">
        <div class="col-badge">${highlightedLetter}</div>
        <div class="col-index-tag">Графа ${col.col_index}</div>
      </div>
      <div class="col-card-body">
        <div class="col-subtitle ${subClass}">${highlightedSub}</div>
        <div class="col-title-text" style="margin-bottom: var(--spacing-sm);">${highlightedMain}</div>
        <div class="col-instruction-section">
          <div class="instruction-title">Інструкція для заповнення:</div>
          <div class="instruction-content">${highlightedInstruction}</div>
        </div>
      </div>
      <div class="card-actions">
        <button class="action-btn copy-btn" title="Копіювати опис" data-text="${col.title_main}">
          <i class="far fa-copy"></i>
        </button>
        <button class="action-btn open-details-btn" title="Детальніше">
          <i class="fas fa-expand-alt"></i>
        </button>
      </div>
    `;
    
    // Attach details click
    card.addEventListener('click', (e) => {
      // Ignore click if copy button is clicked
      if (e.target.closest('.copy-btn')) return;
      openDetails(col);
    });
    
    // Attach copy click
    const copyBtn = card.querySelector('.copy-btn');
    copyBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      copyToClipboard(col.title_main, `Опис графи ${col.col_letter} скопійовано!`);
    });

    grid.appendChild(card);
  });
  
  resultsContainer.appendChild(grid);
}

// Render Compact Table
function renderTable(data) {
  const container = document.createElement('div');
  container.className = 'table-view-container fade-in-item';
  
  const table = document.createElement('table');
  table.className = 'columns-table';
  
  table.innerHTML = `
    <thead>
      <tr>
        <th style="width: 1%; white-space: nowrap;">Літера</th>
        <th style="width: 1%; white-space: nowrap;">Графа</th>
        <th style="width: 1%; white-space: nowrap;">Півріччя</th>
        <th style="width: 48%;">Назва / Опис графи</th>
        <th style="width: 48%;">Інструкція для заповнення</th>
        <th style="width: 1%; white-space: nowrap; text-align: center;">Дії</th>
      </tr>
    </thead>
    <tbody>
    </tbody>
  `;
  
  const tbody = table.querySelector('tbody');
  
  data.forEach(col => {
    const tr = document.createElement('tr');
    tr.id = `col-${col.col_letter}`;
    
    // Determine subtitle styling
    const subClass = col.title_sub === '1-е півріччя' ? 'first-half' : 'second-half';
    const shortSubText = col.title_sub === '1-е півріччя' ? '1' : (col.title_sub === '2-е півріччя' ? '2' : '—');
    
    const highlightedMain = highlightText(col.title_main, state.searchTerm);
    const highlightedSubShort = highlightText(shortSubText, state.searchTerm);
    const highlightedLetter = highlightText(col.col_letter, state.searchTerm);
    const highlightedInstruction = highlightText(col.instruction, state.searchTerm);
    
    tr.innerHTML = `
      <td class="col-letter-cell" style="white-space: nowrap;">${highlightedLetter}</td>
      <td style="white-space: nowrap; text-align: center;"><strong>${col.col_index}</strong></td>
      <td style="white-space: nowrap; text-align: center;"><span class="col-subtitle ${subClass}">${highlightedSubShort}</span></td>
      <td><div class="col-title-text">${highlightedMain}</div></td>
      <td><div style="font-size: 0.8rem; color: var(--text-secondary);">${highlightedInstruction}</div></td>
      <td style="text-align: center; white-space: nowrap;">
        <button class="table-action-btn copy-btn" data-text="${col.title_main}" title="Копіювати опис">
          <i class="far fa-copy"></i>
        </button>
      </td>
    `;
    
    // Row click opens details
    tr.addEventListener('click', (e) => {
      if (e.target.closest('.copy-btn')) return;
      openDetails(col);
    });
    
    // Attach copy click
    const copyBtn = tr.querySelector('.copy-btn');
    copyBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      copyToClipboard(col.title_main, `Опис графи ${col.col_letter} скопійовано!`);
    });
    
    tbody.appendChild(tr);
  });
  
  container.appendChild(table);
  resultsContainer.appendChild(container);
}

// Open details Modal
function openDetails(col) {
  modalColLetter.textContent = col.col_letter;
  modalColIndex.textContent = col.col_index;
  modalColMain.textContent = col.title_main;
  modalColSub.textContent = col.title_sub || 'Не вказано';
  modalColInstruction.textContent = col.instruction;
  
  // Set up copy action inside modal
  modalCopyBtn.onclick = () => {
    const copyTextStr = `Графа ${col.col_letter} (Індекс ${col.col_index}) - ${col.title_sub || 'Загальне'}\n\nОпис: ${col.title_main}\n\nІнструкція: ${col.instruction}`;
    copyToClipboard(copyTextStr, `Повний опис графи ${col.col_letter} скопійовано!`);
  };
  
  modalOverlay.classList.add('show');
}

// Close modal
function closeModal() {
  modalOverlay.classList.remove('show');
}

// Theme Logic
function toggleTheme() {
  const newTheme = state.theme === 'dark' ? 'light' : 'dark';
  setTheme(newTheme);
}

// Toast & Copy Logic
function copyToClipboard(text, successMsg) {
  navigator.clipboard.writeText(text).then(() => {
    showToast(successMsg, 'success');
  }).catch(err => {
    console.error('Copy failed: ', err);
    // Fallback
    const textarea = document.createElement('textarea');
    textarea.value = text;
    document.body.appendChild(textarea);
    textarea.select();
    try {
      document.execCommand('copy');
      showToast(successMsg, 'success');
    } catch (e) {
      showToast('Не вдалося скопіювати текст', 'danger');
    }
    document.body.removeChild(textarea);
  });
}

function showToast(message, type = 'success') {
  toastNotification.textContent = message;
  toastNotification.className = 'toast';
  
  if (type === 'success') {
    toastNotification.classList.add('success');
  } else {
    toastNotification.classList.add('danger');
  }
  
  toastNotification.classList.add('show');
  
  // Hide after 3 seconds
  setTimeout(() => {
    toastNotification.classList.remove('show');
  }, 3000);
}
